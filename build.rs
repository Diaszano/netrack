use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR not set");
    let web_dir = Path::new(&manifest_dir).join("web");

    println!("cargo:rerun-if-changed=web");

    let mut files = Vec::new();
    if web_dir.exists() {
        collect_files(&web_dir, &web_dir, &mut files);
    }
    files.sort_by(|a, b| a.0.cmp(&b.0));

    // Synthesize /locales/index.json from web/locales/*.json
    let locales_dir = web_dir.join("locales");
    let mut locales = Vec::new();
    if locales_dir.exists()
        && let Ok(entries) = fs::read_dir(&locales_dir)
    {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_file()
                && path.extension().and_then(|s| s.to_str()) == Some("json")
                && let Some(file_stem) = path.file_stem().and_then(|s| s.to_str())
            {
                if file_stem == "index" {
                    continue;
                }
                if let Ok(content) = fs::read_to_string(&path)
                    && let Some(name) = extract_meta_name(&content)
                {
                    locales.push((file_stem.to_string(), name));
                }
            }
        }
    }
    locales.sort_by(|a, b| a.0.cmp(&b.0));

    let mut json_out = String::from("[\n");
    for (i, (code, name)) in locales.iter().enumerate() {
        if i > 0 {
            json_out.push_str(",\n");
        }
        json_out.push_str(&format!(
            "  {{\"code\": \"{}\", \"name\": \"{}\"}}",
            escape_json(code),
            escape_json(name)
        ));
    }
    json_out.push_str("\n]\n");

    let locales_index_path = Path::new(&out_dir).join("locales_index.json");
    fs::write(&locales_index_path, &json_out).expect("failed to write locales_index.json");

    // Generate web_assets.rs
    let mut code = String::new();
    code.push_str("// Generated by build.rs. Do not edit.\n\n");
    code.push_str("pub static ASSETS: &[(&str, &str, &[u8])] = &[\n");

    let mut asset_entries: Vec<(String, &'static str, String)> = Vec::new();

    for (url_path, rel_path, file_sys_path) in files {
        println!("cargo:rerun-if-changed={}", file_sys_path.display());
        let mime = mime_type(&rel_path);
        let include_expr = format!(
            "include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{}\"))",
            rel_path.replace('\\', "/")
        );
        asset_entries.push((url_path, mime, include_expr));
    }

    // Add synthesized /locales/index.json
    asset_entries.push((
        "/locales/index.json".to_string(),
        "application/json; charset=utf-8",
        "include_bytes!(concat!(env!(\"OUT_DIR\"), \"/locales_index.json\"))".to_string(),
    ));

    asset_entries.sort_by(|a, b| a.0.cmp(&b.0));

    for (url, mime, expr) in asset_entries {
        code.push_str(&format!("    (\"{}\", \"{}\", {}),\n", url, mime, expr));
    }
    code.push_str("];\n");

    let out_file = Path::new(&out_dir).join("web_assets.rs");
    fs::write(&out_file, &code).expect("failed to write web_assets.rs");
}

fn collect_files(root: &Path, current: &Path, out: &mut Vec<(String, String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(current) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            if let Ok(rel) = path.strip_prefix(root) {
                // Ignore web/tests directory
                if rel.starts_with("tests") {
                    continue;
                }
            }
            collect_files(root, &path, out);
        } else if path.is_file()
            && let Ok(rel) = path.strip_prefix(root)
        {
            if rel.starts_with("tests") {
                continue;
            }
            let rel_str = rel.to_string_lossy().replace('\\', "/");
            let url_path = format!("/{}", rel_str);
            let manifest_rel_path = format!("web/{}", rel_str);
            out.push((url_path, manifest_rel_path, path.clone()));
        }
    }
}

fn mime_type(path: &str) -> &'static str {
    if path.ends_with(".html") {
        "text/html; charset=utf-8"
    } else if path.ends_with(".css") {
        "text/css"
    } else if path.ends_with(".js") {
        "text/javascript"
    } else if path.ends_with(".json") {
        "application/json; charset=utf-8"
    } else if path.ends_with(".woff2") {
        "font/woff2"
    } else if path.ends_with(".svg") {
        "image/svg+xml"
    } else if path.ends_with(".png") {
        "image/png"
    } else if path.ends_with(".ico") {
        "image/x-icon"
    } else {
        "application/octet-stream"
    }
}

fn extract_meta_name(content: &str) -> Option<String> {
    let meta_idx = content.find("\"_meta\"")?;
    let rest = &content[meta_idx..];
    let open_brace = rest.find('{')?;
    let after_brace = &rest[open_brace..];
    let close_brace = after_brace.find('}')?;
    let meta_obj = &after_brace[..close_brace];
    let name_idx = meta_obj.find("\"name\"")?;
    let after_name = &meta_obj[name_idx + 6..];
    let colon_idx = after_name.find(':')?;
    let val_str = after_name[colon_idx + 1..].trim();
    if !val_str.starts_with('"') {
        return None;
    }
    let rest_val = &val_str[1..];
    let mut name = String::new();
    let mut escape = false;
    for c in rest_val.chars() {
        if escape {
            name.push(c);
            escape = false;
        } else if c == '\\' {
            escape = true;
        } else if c == '"' {
            break;
        } else {
            name.push(c);
        }
    }
    Some(name)
}

fn escape_json(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out
}
